<?php
/**
 * Build a fresh local WordPress site for the WriteNow server tests.
 *
 * Usage: php setup-site.php <site-dir> <wordpress-core-dir> <sqlite-repo-dir> <port>
 *
 * The site lives outside the repository. It runs on SQLite, has the real
 * `shortnotes` and `likes` plugins and the `writemore` theme symlinked from
 * their sibling checkouts, and loads this repository's `mu-plugins/` and
 * `advanced-cache.php` (Batcache) directly. Everything is rebuilt each run.
 *
 * @package jeremyfelt
 */

// phpcs:disable WordPress.WP.AlternativeFunctions -- A command-line build script that runs before WordPress exists.

if ( 'cli' !== PHP_SAPI || $argc < 5 ) {
	fwrite( STDERR, "Usage: php setup-site.php <site-dir> <wordpress-core-dir> <sqlite-repo-dir> <port>\n" );
	exit( 1 );
}

$site_dir   = rtrim( $argv[1], '/' );
$core_dir   = rtrim( $argv[2], '/' );
$sqlite_dir = rtrim( $argv[3], '/' );
$port       = (int) $argv[4];
$repo_dir   = dirname( __DIR__, 3 );
$siblings   = dirname( $repo_dir );
$tests_dir  = dirname( __DIR__ );

/**
 * Run a shell command and stop if it fails.
 *
 * @param string $command The command.
 */
function run( string $command ): void {
	passthru( $command, $code ); // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.system_calls_passthru -- A local build script.

	if ( 0 !== $code ) {
		fwrite( STDERR, "Command failed ($code): $command\n" );
		exit( 1 );
	}
}

/**
 * Create a symlink, replacing anything already at the link path.
 *
 * @param string $target The existing file or directory.
 * @param string $link   The link to create.
 */
function link_to( string $target, string $link ): void {
	if ( ! file_exists( $target ) ) {
		fwrite( STDERR, "Missing: $target\n" );
		exit( 1 );
	}

	run( 'rm -rf ' . escapeshellarg( $link ) );
	symlink( $target, $link );
}

foreach ( [ 'shortnotes', 'likes', 'writemore' ] as $sibling ) {
	if ( ! is_dir( "$siblings/$sibling" ) ) {
		fwrite( STDERR, "The $sibling checkout must sit beside jeremyfelt.com, at $siblings/$sibling.\n" );
		exit( 1 );
	}
}

run( 'rm -rf ' . escapeshellarg( $site_dir ) );
mkdir( $site_dir . '/database', 0777, true );
run( 'cp -R ' . escapeshellarg( $core_dir ) . ' ' . escapeshellarg( "$site_dir/wordpress" ) );
run( 'rm -rf ' . escapeshellarg( "$site_dir/wordpress/.git" ) );

$content = "$site_dir/wordpress/wp-content";

// The SQLite database drop-in.
$plugin = "$sqlite_dir/packages/plugin-sqlite-database-integration";
run( 'cp -RL ' . escapeshellarg( $plugin ) . ' ' . escapeshellarg( "$content/plugins/sqlite-database-integration" ) );

$db_php = (string) file_get_contents( "$plugin/db.copy" );
$db_php = str_replace( "'{SQLITE_IMPLEMENTATION_FOLDER_PATH}'", "__DIR__ . '/plugins/sqlite-database-integration'", $db_php );
$db_php = str_replace( '{SQLITE_PLUGIN}', 'sqlite-database-integration/load.php', $db_php );
file_put_contents( "$content/db.php", $db_php );

// The code under test, linked rather than copied so the tests always see the working tree.
link_to( "$repo_dir/mu-plugins", "$content/mu-plugins" );
link_to( "$repo_dir/advanced-cache.php", "$content/advanced-cache.php" );
link_to( "$siblings/shortnotes", "$content/plugins/shortnotes" );
link_to( "$siblings/likes", "$content/plugins/likes" );
link_to( "$siblings/writemore", "$content/themes/writemore" );
link_to( "$tests_dir/support/test-helpers.php", "$content/plugins/writenow-test-helpers.php" );
link_to( "$tests_dir/support/object-cache.php", "$content/object-cache.php" );

$home = "http://127.0.0.1:$port";
$keys = '';

foreach ( [ 'AUTH_KEY', 'SECURE_AUTH_KEY', 'LOGGED_IN_KEY', 'NONCE_KEY', 'AUTH_SALT', 'SECURE_AUTH_SALT', 'LOGGED_IN_SALT', 'NONCE_SALT' ] as $key ) {
	$keys .= "define( '$key', '" . bin2hex( random_bytes( 32 ) ) . "' );\n";
}

$config = <<<PHP
<?php
// Generated by tests/writenow/bin/setup-site.php. Local test site only.
define( 'DB_NAME', 'WordPress' );
define( 'DB_USER', '' );
define( 'DB_PASSWORD', '' );
define( 'DB_HOST', '' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );
define( 'DB_DIR', __DIR__ . '/database/' );
define( 'DB_FILE', '.ht.sqlite' );
$keys
\$table_prefix = 'wp_';

define( 'WP_HOME', '$home' );
define( 'WP_SITEURL', '$home' );
define( 'WP_ENVIRONMENT_TYPE', 'local' );

// Load this repository's mu-plugins from the working tree, and give them a URL through the symlink.
define( 'WPMU_PLUGIN_DIR', '$repo_dir/mu-plugins' );
define( 'WPMU_PLUGIN_URL', '$home/wp-content/mu-plugins' );

// Batcache runs for web requests, as in production. The CLI runner has no request to cache.
define( 'WP_CACHE', 'cli' !== PHP_SAPI );
define( 'WRITENOW_TEST_CACHE_DIR', __DIR__ . '/object-cache/' );

// Nothing leaves this machine.
define( 'WP_HTTP_BLOCK_EXTERNAL', true );
define( 'DISABLE_WP_CRON', true );
define( 'AUTOMATIC_UPDATER_DISABLED', true );
define( 'WP_AUTO_UPDATE_CORE', false );

define( 'WP_DEBUG', true );
define( 'WP_DEBUG_LOG', __DIR__ . '/debug.log' );
define( 'WP_DEBUG_DISPLAY', false );

if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', __DIR__ . '/wordpress/' );
}

require_once ABSPATH . 'wp-settings.php';

PHP;

file_put_contents( "$site_dir/wp-config.php", $config );

// Install WordPress in a separate process, now that the config exists.
run( 'php ' . escapeshellarg( __DIR__ . '/install-site.php' ) . ' ' . escapeshellarg( $site_dir ) );
